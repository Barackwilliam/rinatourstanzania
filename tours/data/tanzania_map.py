"""
Tanzania outline for the routes map.

Boundary data simplified from public country GeoJSON with Ramer-Douglas-Peucker,
then projected once here. Destination markers use the SAME project() function,
so a marker placed from its real latitude/longitude lands in the right spot on
the outline. Change the projection and both move together.
"""

VIEWBOX = "0 0 620 600"

LON_MIN, LON_MAX = 29.3, 40.55
LAT_MIN, LAT_MAX = -11.85, -0.9
WIDTH, HEIGHT, PAD = 620.0, 600.0, 14.0


def project(lon, lat):
    """Longitude/latitude -> SVG user units, rounded to one decimal."""
    x = PAD + (lon - LON_MIN) / (LON_MAX - LON_MIN) * (WIDTH - 2 * PAD)
    y = PAD + (LAT_MAX - lat) / (LAT_MAX - LAT_MIN) * (HEIGHT - 2 * PAD)
    return round(x, 1), round(y, 1)


